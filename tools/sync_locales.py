def merge(base: dict[str, str], existing: dict[str, str], overlay: dict[str, str]) -> dict[str, str]:
    out = dict(base)  # fallback to Russian if somehow missing
    out.update(existing)
    out.update(overlay)
    out.update(LANG)
    return out


def main() -> None:
    order = load_order(BASE)
    base = parse_strings(BASE)
    assert len(order) == len(base), (len(order), len(base))

    configs = [
        ("values-en", "en", EN_OVERLAY, False),
        ("values-ru", "ru", {}, True),  # sync from base
        ("values-es", "es", ES_FULL_FIXES, True),  # full rewrite via overlay
        ("values-zh", "zh", ZH_OVERLAY, False),
        ("values-ja", "ja", JA_OVERLAY, False),
        ("values-ko", "ko", KO_OVERLAY, False),
    ]

    for folder, code, overlay, replace_from_base in configs:
        path = RES / folder / "strings.xml"
        existing = parse_strings(path) if path.exists() else {}
        if replace_from_base and folder == "values-es":
            values = dict(base)
            values.update(overlay)
        elif folder == "values-ru":
            values = dict(base)
            values.update(existing)
            # Prefer base text for keys that were only in base (already in values)
            for k in order:
                if k not in existing:
                    values[k] = base[k]
        else:
            values = merge(base, existing, overlay)

        word, msg = WIPE_WORD[code]
        values["wipe_data_confirm_word"] = word
        values["wipe_data_confirm_message"] = msg
        values.update(LANG)
        if folder == "values-es":
            values.update(overlay)
            values.update(LANG)
            values["wipe_data_confirm_word"] = word
            values["wipe_data_confirm_message"] = msg

        missing = [k for k in order if k not in values]
        if missing:
            raise SystemExit(f"{folder} missing after merge: {missing[:20]} ... ({len(missing)})")
        write_strings(path, order, {k: values[k] for k in order})
        print(f"wrote {folder} ({len(order)} keys)")

    print("done")


if __name__ == "__main__":
    main()
