def parse_strings(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    # Capture name and inner XML text (may contain entities)
    pattern = re.compile(
        r'<string\s+name="([^"]+)"\s*>(.*?)</string>',
        re.DOTALL,
    )
    out: dict[str, str] = {}
    for m in pattern.finditer(text):
        out[m.group(1)] = m.group(2)
    return out


def xml_escape_keep_entities(s: str) -> str:
    # Values already may contain &amp; etc. from source; write as-is from our dicts
    return s


def write_strings(path: Path, ordered_keys: list[str], values: dict[str, str]) -> None:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for k in ordered_keys:
        v = values[k]
        lines.append(f'    <string name="{k}">{v}</string>')
    lines.append("</resources>")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def load_order(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    return re.findall(r'<string\s+name="([^"]+)"', text)


